<p>第一种最常见，先把两组概念分开：</p>
<ul>
<li><strong>最好 / 最坏 / 平均情况</strong>说的是“挑哪种输入”。二分查找的最好情况是目标正好在中间，最坏情况是查到最后才找到或找不到。</li>
<li><strong>O、Ω、Θ</strong> 说的是“增长的界”：O 是上界（最多这么慢），Ω 是下界（至少这么慢），Θ 是上下界同时成立（就是这个量级）。</li>
