<li><strong>题型</strong>：单选“哪一项<strong>不</strong>正确”；多选“选出所有正确的说法 / 所有合法的拓扑序”；判断带“总是”“一定”“任意”的句子；匹配题把算法和前提配对。</li>
<li><strong>先圈限定词</strong>：“一棵 BST”指任意 BST，最坏 O(n)；不分情况的 Θ 要对所有输入成立；“根满足”不等于“每个结点满足”；看清问的是 O 还是 Ω。</li>
<li><strong>判错靠反例</strong>：三角形（DFS 不求最短路，MST ≠ 最短路）、2₁ 2₂ 1（选择排序不稳定）、根下两条等长长链（只查根不算平衡，查找仍约 n/2 步）、带权的四顶点环（BFS 不能用于带权图）。</li>
