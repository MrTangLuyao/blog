<p>两列的比值正好是 1/(1−α)：α = 0.5 时差 2 倍，0.9 时差 10 倍。α 接近 1 时两列都冲向无穷。反过来，只要把 α 压在某个常数以下，平均插入和查找就是 <strong>O(1)</strong>。这是平均情况，最坏仍是 O(n)。</p>

